"""Generate container connection overrides without changing the host configuration."""

import os
import tempfile
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

from sqlalchemy.engine import make_url

from docagent.config import Settings


def service_url(value: str, host: str, port: int) -> str:
    parsed = urlsplit(value)
    if not parsed.hostname or not host or any(c in host for c in "/\\@?#\r\n"):
        raise ValueError("Invalid service hostname")
    authority = f"[{host}]" if ":" in host else host
    credentials = parsed.netloc.rsplit("@", 1)[0] + "@" if "@" in parsed.netloc else ""
    return urlunsplit(parsed._replace(netloc=f"{credentials}{authority}:{port}"))


def write_compose_env(
    cfg: Settings,
    output: Path,
    database_host="pgvector",
    redis_host="redis",
    minio_host="minio",
):
    if output.resolve() == Path(".env").resolve():
        raise ValueError("Choose a separate output file; .env must remain the host configuration")
    database = make_url(cfg.database_url)
    if not database.drivername.startswith("postgresql"):
        raise ValueError("Configure a PostgreSQL DOCAGENT_DATABASE_URL before generating Compose settings")
    if not database_host or any(c in database_host for c in "/\\@?#\r\n"):
        raise ValueError("Invalid database hostname")
    values = {
        "DOCAGENT_DATABASE_URL": database.set(host=database_host, port=5432).render_as_string(hide_password=False),
        "DOCAGENT_REDIS_URL": service_url(cfg.redis_url, redis_host, 6379),
    }
    if cfg.storage_backend == "s3" and cfg.s3_endpoint_url:
        values["DOCAGENT_S3_ENDPOINT_URL"] = service_url(cfg.s3_endpoint_url, minio_host, 9000)
    if any("\n" in value or "\r" in value for value in values.values()):
        raise ValueError("Connection URLs must occupy a single line")
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", prefix=".env.compose-", suffix=".tmp",
            dir=output.parent, delete=False,
        ) as stream:
            temporary = Path(stream.name)
            stream.write("# Generated by docagent compose-env. Contains credentials; do not commit.\n")
            for key, value in values.items():
                stream.write(f"{key}={value}\n")
        temporary.chmod(0o600)
        os.replace(temporary, output)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
    return {"output": str(output), "overrides": list(values), "database_host": database_host,
            "redis_host": redis_host, "minio_host": minio_host}
